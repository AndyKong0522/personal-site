/**
 * 3D 卡通形象生成用的提示词
 *
 * 版本命名：
 *   A / B          —— 第一版（素色 T 恤），已生成 avatar-a.glb / avatar-b.glb
 *   B-hoodie 等    —— 换装候选（都戴眼镜，因为本人 2026-10-15 选定 B 版的镜框造型）
 *
 * 迭代记录：
 *  - 第一轮出来是「大头娃娃」儿童比例 → 明确成年人头身比
 *  - B 版脚被裁掉且光脚 → 明确「头顶到鞋底全部可见」+「穿白色运动鞋」+「不要光脚」
 *  - 白 T 恤在白背景上对比度太低，影响生3D 分割 → 改深色上衣
 *  - 本人反馈「衣服太素」→ 按照片里的真实穿搭做多套候选
 *
 * 共同约束的理由：图生 3D 最吃「轮廓干净 + 正面 + 弱透视 + 手臂离身」。
 * 手臂贴身会让腋下和身体粘连；强透视会让比例失真；背景有杂物会被一起建模进去。
 */

const STYLE = `把照片里的人做成 3D 卡通角色设定图，皮克斯/黏土动画质感，五官和发型要像本人。`
const PROPORTION = `比例：写实成年人比例，头身比约 1:6.5，不要 Q 版、大头娃娃或儿童比例。`
const POSE = `姿态：正面站立面向镜头，双臂微微离开身体成 A 字（手臂与躯干之间要有明显空隙，不要贴着），双脚与肩同宽、脚掌朝前，表情平静友好地微笑。`

/** 更大张开的站姿（第二轮优化用）。
 *
 *  为什么改：现用模型（B-hoodie）出来以后有两个问题都源于网格本身——
 *  ① 挥手抬臂时，袖子与躯干之间的接缝会裂开一条细缝（腋下拓扑不够）；
 *  ② 头明显探在胸前，看着像驼背前倾（Neck→Head 骨段前倾 22.8°）。
 *  这两点都是"AI 从参考图猜出来"的，所以只能从参考图下手：
 *    · 手臂张到 35–40°、腋下能透出背景 → 生3D 时手臂和躯干会被分开建模
 *    · 明确"背脊挺直、胸口打开、下巴水平、头不前伸" → 减少前探和驼背
 */
const POSE_OPEN = `姿态：正面站立面向镜头，双臂向外张开约 35 到 40 度、手肘自然微屈，手臂与躯干之间留出很大空隙、腋下能直接透出背景（手不要贴住身体、不要插兜）；肩膀自然下沉放松、不要耸肩，背脊挺直、胸口打开、不要含胸驼背，头部摆正、顺势落在肩膀正上方、不要前伸，下巴与地面平行、不要仰头也不要低头；双脚与肩同宽、脚掌朝前，表情平静友好地微笑。`
const FRAMING = `取景：全身完整入镜，从头顶到鞋底全部可见，上下留少量白边，弱透视（接近正交），不要广角变形。`
const BG = `背景：纯白色，干净，无阴影、无地面、无道具。`
const NO = `不要：手持物品、背包、帽子、首饰、光脚。`
const GLASSES = `眼镜：戴一副黑色粗框眼镜，只要镜框，完全不要镜片（镜片区域完全透明、不存在），镜框不能遮挡或变形眼睛，线条干净、不反光。`

/** 头发：3D 生成器天生爱把头发做得又高又蓬，出来跟 2D 图差很远。
 *  所以这里反复往下压——"贴头骨、发量少、顶部扁平、只比头骨高一点点"。 */
const HAIR = `头发：**短而服帖的侧分短发**，紧贴头骨、整体轮廓顺着头形，发量偏少、**顶部扁平**，两侧和后面剪短、露出耳朵，刘海自然垂在一侧；**不要蓬松、不要高耸、不要大背头、不要爆炸头**，头顶最高点只比头骨高一点点，整体比头骨略大一圈即可。`

/** 平滑面料外套（替换灯芯绒）。
 *  灯芯绒那种细密竖棱会被生3D 建成大量细碎几何，模型表面因此出现层叠的碎面片；
 *  换成平滑布料后网格干净得多。色调和款式尽量保持原来那套的感觉。 */
const OUTFIT_SMOOTH =
  `浅卡其色（驼色）**平滑面料**的工装夹克，布料表面光滑、**没有任何纹理、没有竖条棱、没有灯芯绒**，` +
  `敞开不系扣；里面一件浅灰色纯色长袖卫衣，` +
  `深灰色直筒长裤，白色运动鞋。无图案、无文字、无 logo。`

/** 拼一套「戴眼镜 + 指定服装」的提示词 */
const withOutfit = (outfit) =>
  [STYLE, PROPORTION, POSE, `服装：${outfit}`, FRAMING, BG, GLASSES, NO].join('\n')

/** 同上，但用张得更开的站姿 */
const withOutfitOpen = (outfit) =>
  [STYLE, PROPORTION, POSE_OPEN, `服装：${outfit}`, FRAMING, BG, GLASSES, NO].join('\n')

